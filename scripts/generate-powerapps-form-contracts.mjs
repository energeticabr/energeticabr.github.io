import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const INVENTORY_PATH = join(ROOT, "docs", "analysis", "powerapps-form-field-parity.md");
const OUTPUT_PATH = join(ROOT, "portal", "catalog", "powerapps-form-contracts.generated.js");

const TECHNICAL_FIELDS = new Set([
  "ID",
  "CONTENTTYPE",
  "ATTACHMENTS",
  "CREATED",
  "MODIFIED",
  "AUTHOR",
  "EDITOR",
  "COMPLIANCEASSETID",
  "UIVERSIONSTRING",
  "GUID",
]);

const MANUAL_FIELD_REPLACEMENTS = Object.freeze({
  lancamentos: Object.freeze({ Title: "FILIAL" }),
});

function canonicalFieldName(value) {
  return String(value || "")
    .replace(/_x([0-9a-f]{4})_/gi, (_match, code) => String.fromCodePoint(Number.parseInt(code, 16)))
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/^_+|_+$/g, "")
    .replace(/[^A-Za-z0-9]/g, "")
    .toLocaleUpperCase("pt-BR");
}

function isTechnicalField(displayName, internalName) {
  if (/^\{.+\}$/.test(internalName)) return true;
  return TECHNICAL_FIELDS.has(canonicalFieldName(internalName))
    || TECHNICAL_FIELDS.has(canonicalFieldName(displayName));
}

function fieldsFromSection(section, entityId) {
  const fieldsLine = section.match(/^- \*\*Campos visíveis:\*\* (.+)\.\r?$/m)?.[1] || "";
  const replacements = MANUAL_FIELD_REPLACEMENTS[entityId] || {};
  const fields = [];
  const seen = new Set();

  for (const match of fieldsLine.matchAll(/\*\*(.+?)\*\*(?: \(`([^`]+)`\))?/g)) {
    const displayName = match[1];
    const inventoriedName = match[2] || displayName;
    if (isTechnicalField(displayName, inventoriedName)) continue;
    const fieldName = replacements[inventoriedName] || inventoriedName;
    if (seen.has(fieldName)) continue;
    fields.push(fieldName);
    seen.add(fieldName);
  }

  return fields;
}

export function extractPowerAppsFormFields(inventory) {
  const contracts = {};

  for (const section of inventory.split(/(?=^### )/m)) {
    const entityId = section.match(/^- \*\*Entidade no portal:\*\* .+?\(`([^`]+)`\)\.\r?$/m)?.[1];
    const formCount = Number(section.match(/^- \*\*Evidência de gravação:\*\* (\d+) formulário\(s\)/m)?.[1] || 0);
    if (!entityId || formCount < 1) continue;
    contracts[entityId] = fieldsFromSection(section, entityId);
  }

  return contracts;
}

export function renderPowerAppsFormContracts(contracts) {
  const lines = [
    "// Generated by scripts/generate-powerapps-form-contracts.mjs.",
    "// Source: docs/analysis/powerapps-form-field-parity.md",
    "",
    "const POWERAPPS_FORM_FIELDS = Object.freeze({",
  ];

  for (const entityId of Object.keys(contracts).sort()) {
    lines.push(`  ${JSON.stringify(entityId)}: Object.freeze([`);
    for (const fieldName of contracts[entityId]) lines.push(`    ${JSON.stringify(fieldName)},`);
    lines.push("  ]),");
  }

  lines.push("});", "", "export default POWERAPPS_FORM_FIELDS;", "");
  return lines.join("\n");
}

async function main() {
  const inventory = await readFile(INVENTORY_PATH, "utf8");
  const output = renderPowerAppsFormContracts(extractPowerAppsFormFields(inventory));
  if (process.argv.includes("--check")) {
    const current = await readFile(OUTPUT_PATH, "utf8").catch(() => "");
    if (current !== output) {
      process.stderr.write("Power Apps form contracts are out of date.\n");
      process.exitCode = 1;
    }
    return;
  }
  await writeFile(OUTPUT_PATH, output, "utf8");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
